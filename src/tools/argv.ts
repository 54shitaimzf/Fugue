// 一行命令 → 要 spawn 的那串参数。**这一版是"交给 shell"**：`/bin/sh -c <line>`。
//
// **为什么它自己一个文件**：它有两个调用方，而那两个调用方之间有一条值上的环——
// `tools/host.ts`（工具面的实现）要它，`capability/dispatch.ts`（工具面的门）也要它。住在
// `dispatch.ts` 里的时候，`host.ts → dispatch.ts` 那一条是真的值引用，于是模块图成一个环：
// `node --test` 一次把 56 个测试文件全载进同一个进程时解不开（实测那样跑会**静默丢掉 7 条**
// ——`tests 325` 而不是 `332`，退出码 0）。这一份没有依赖，谁都能引用它。
//
// 为什么不自己切词：切词的第一步就是一套 shell 语法（引号 · 展开 · 管道 · 重定向），而"我们
// 自己实现半个 shell"是更坏的选择。**真正的边界在沙箱那一层**（`M7` 包命令行），不在这一层
// 切词；这与架构 § 8.10 里 `bash` 的收法一致——它收的就是一行命令。
export function shellArgv(line: string): string[] {
  return ['/bin/sh', '-c', line]
}
